-- ============================================
-- 1. AUTOMATIC ID GENERATION
-- ============================================

ALTER TABLE public.admins
ALTER COLUMN admin_id
ADD GENERATED BY DEFAULT AS IDENTITY;

ALTER TABLE public.citizens
ALTER COLUMN citizen_id
ADD GENERATED BY DEFAULT AS IDENTITY;

ALTER TABLE public.document_types
ALTER COLUMN document_type_id
ADD GENERATED BY DEFAULT AS IDENTITY;

ALTER TABLE public.requirements
ALTER COLUMN requirement_id
ADD GENERATED BY DEFAULT AS IDENTITY;

ALTER TABLE public.document_requests
ALTER COLUMN request_id
ADD GENERATED BY DEFAULT AS IDENTITY;

ALTER TABLE public.request_status_history
ALTER COLUMN history_id
ADD GENERATED BY DEFAULT AS IDENTITY;


-- ============================================
-- 2. SYNCHRONIZE ID GENERATORS
-- WITH EXISTING RECORDS
-- ============================================

SELECT setval(
               pg_get_serial_sequence('public.admins', 'admin_id')::regclass,
               COALESCE(MAX(admin_id), 1),
               MAX(admin_id) IS NOT NULL
       )
FROM public.admins;

SELECT setval(
               pg_get_serial_sequence('public.citizens', 'citizen_id')::regclass,
               COALESCE(MAX(citizen_id), 1),
               MAX(citizen_id) IS NOT NULL
       )
FROM public.citizens;

SELECT setval(
               pg_get_serial_sequence('public.document_types', 'document_type_id')::regclass,
               COALESCE(MAX(document_type_id), 1),
               MAX(document_type_id) IS NOT NULL
       )
FROM public.document_types;

SELECT setval(
               pg_get_serial_sequence('public.requirements', 'requirement_id')::regclass,
               COALESCE(MAX(requirement_id), 1),
               MAX(requirement_id) IS NOT NULL
       )
FROM public.requirements;

SELECT setval(
               pg_get_serial_sequence('public.document_requests', 'request_id')::regclass,
               COALESCE(MAX(request_id), 1),
               MAX(request_id) IS NOT NULL
       )
FROM public.document_requests;

SELECT setval(
               pg_get_serial_sequence('public.request_status_history', 'history_id')::regclass,
               COALESCE(MAX(history_id), 1),
               MAX(history_id) IS NOT NULL
       )
FROM public.request_status_history;


-- ============================================
-- 3. ALLOW SYSTEM-GENERATED STATUS HISTORY
-- WITHOUT AN ADMINISTRATOR
-- ============================================

ALTER TABLE public.request_status_history
    ALTER COLUMN admin_id DROP NOT NULL;